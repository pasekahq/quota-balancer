//! RFC 3339 parsing agrees with known Unix times and rejects impossible or incomplete stamps.

use qb_vendors::rfc3339::{InvalidTimestamp, parse};

#[test]
fn known_unix_times() {
    let cases = [
        ("1970-01-01T00:00:00Z", 0),
        ("2000-03-01T00:00:00+02:00", 951_861_600),
        ("1999-12-31T23:59:59Z", 946_684_799),
        ("2027-01-15T08:00:00Z", 1_800_000_000),
        ("2027-01-15t08:00:00z", 1_800_000_000),
        ("2027-01-15 08:00:00Z", 1_800_000_000),
        ("2027-01-15T13:30:00+05:30", 1_800_000_000),
        ("2027-01-15T02:30:00-05:30", 1_800_000_000),
        ("2027-01-15T08:00:00.5Z", 1_800_000_000),
        ("2027-01-15T08:00:00.999999999Z", 1_800_000_000),
        ("2027-01-15T10:00:00.250+02:00", 1_800_000_000),
        ("2024-02-29T12:00:00Z", 1_709_208_000),
        ("2000-02-29T00:00:00Z", 951_782_400),
        ("2100-03-01T00:00:00Z", 4_107_542_400),
        ("1970-01-01T01:00:00+01:00", 0),
    ];
    for (text, want) in cases {
        assert_eq!(parse(text), Ok(want), "{text}");
    }
}

#[test]
fn rejects_impossible_and_incomplete_stamps() {
    let cases = [
        "2027-02-30T00:00:00Z",
        "2023-02-29T00:00:00Z",
        "2100-02-29T00:00:00Z",
        "2027-04-31T00:00:00Z",
        "2027-13-01T00:00:00Z",
        "2027-00-10T00:00:00Z",
        "2027-01-00T00:00:00Z",
        "2027-01-15T24:00:00Z",
        "2027-01-15T08:60:00Z",
        "2027-01-15T08:00:61Z",
        "2027-01-15T08:00:00",
        "2027-01-15T08:00:00.Z",
        "2027-01-15T08:00:00+0200",
        "2027-01-15T08:00:00+24:00",
        "2027-01-15T08:00:00+02:60",
        "2027-01-15T08:00:00Z ",
        "2027-01-15X08:00:00Z",
        "2027-1-15T08:00:00Z",
        "+027-01-15T08:00:00Z",
        "1969-12-31T23:59:59Z",
        "1970-01-01T00:30:00+01:00",
        "",
        "2027-01-15",
        "２０２７-01-15T08:00:00Z",
    ];
    for text in cases {
        assert_eq!(parse(text), Err(InvalidTimestamp), "{text}");
    }
}
